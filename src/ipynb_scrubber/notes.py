import re

from pathlib import Path

from .exceptions import ScrubberError

#: Fence info string for notebooks that declare no kernel language.
DEFAULT_NOTE_LANGUAGE = 'python'

#: The shortest fence Markdown recognises.
MIN_FENCE = 3

_BACKTICK_RUN = re.compile(r'`+')


def _fence_for(content: str) -> str:
    """A backtick fence that ``content`` cannot terminate early.

    CommonMark closes a fenced block at the first backtick run at least as long
    as the opening one, so the fence must be longer than any run inside the
    arbitrary source being fenced.
    """
    longest = max(
        (len(run.group()) for run in _BACKTICK_RUN.finditer(content)),
        default=0,
    )
    return '`' * max(MIN_FENCE, longest + 1)


def render_notes(notes_dict: dict[str, str], language: str | None = None) -> str:
    """Render collected cell notes as a Markdown document.

    ``language`` is the fence info string; ``None`` uses
    :data:`DEFAULT_NOTE_LANGUAGE`.
    """
    info = language or DEFAULT_NOTE_LANGUAGE
    parts = [
        '# Notebook Notes\n\n',
        'This file contains the original content of cells marked for note-taking.\n\n',
    ]

    for note_id, content in notes_dict.items():
        fence = _fence_for(content)
        parts.append(f'## {note_id}\n\n')
        parts.append(f'{fence}{info}\n')
        parts.append(content)
        if not content.endswith('\n'):
            parts.append('\n')
        parts.append(f'{fence}\n\n')

    parts.append('---\n')
    parts.append('*Generated by ipynb-scrubber*\n')

    return ''.join(parts)


def require_destination(
    note_count: int,
    destination: Path | None,
    note_tag: str,
    remedy: str,
) -> None:
    """Refuse to emit notes that have nowhere to go.

    The exercise notebook refers to each noted cell by id, so those references
    would dangle.

    ``remedy`` closes the message by telling this front end's caller how to name
    a destination, since a flag and a config key are not the same advice.

    Raises:
        ScrubberError: If notes were collected without a ``destination``.
    """
    if note_count and destination is None:
        raise ScrubberError(
            f'Found {note_count} cell(s) with note tag "{note_tag}", but '
            f'nowhere to save the notes. {remedy}',
        )
