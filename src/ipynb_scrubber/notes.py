from pathlib import Path

from .exceptions import ProcessingError


def write_notes_file(
    notes_dict: dict[str, tuple[str, str]],
    output_path: Path,
) -> None:
    """Write collected cell notes to a Markdown file.

    Args:
        notes_dict: Map of note_id -> (cell_type, content). Notes are only
            ever collected from code cells, so content is always Python.
        output_path: Path where notes file will be written

    Raises:
        ProcessingError: If an error occurs while writing notes
    """
    try:
        output_path.parent.mkdir(parents=True, exist_ok=True)

        with output_path.open('w') as f:
            f.write('# Notebook Notes\n\n')
            f.write(
                'This file contains the original content of cells marked '
                'for note-taking.\n\n',
            )

            for note_id, (_, content) in notes_dict.items():
                f.write(f'## {note_id}\n\n')
                f.write('```python\n')
                f.write(content)
                if not content.endswith('\n'):
                    f.write('\n')
                f.write('```\n\n')

            f.write('---\n')
            f.write('*Generated by ipynb-scrubber*\n')

    except OSError as e:
        raise ProcessingError(f'Error writing notes file: {e}') from e
